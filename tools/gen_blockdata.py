"""Generate packs/BP/scripts/gen/blockdata.js from re/blocktable.txt (dumped from b173.jar by
`Harness tables`): the per-block lookup tables and Material flags the b1.7.3 world generator reads."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Material statics of class ln in declaration order (MCP names for readability).
MATERIALS = ['a:air', 'b:grass', 'c:ground', 'd:wood', 'e:rock', 'f:iron', 'g:water', 'h:lava', 'i:leaves',
             'j:plants', 'k:sponge', 'l:cloth', 'm:fire', 'n:sand', 'o:circuits', 'p:glass', 'q:tnt', 'r:unused',
             's:ice', 't:snow', 'u:craftedSnow', 'v:cactus', 'w:clay', 'x:pumpkin', 'y:portal', 'z:cake',
             'A:web', 'B:piston']


def main():
    rows = []
    for line in open(os.path.join(ROOT, 're', 'blocktable.txt'), encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        left, matf, blkf, name = [p.strip() for p in line.split('|')]
        lp = left.split()
        rows.append({
            'id': int(lp[0]), 'cls': lp[1], 'mat': lp[2], 'o': int(lp[3]), 'q': int(lp[4]), 's': int(lp[5]),
            'n': int(lp[6]), 'p': int(lp[7]), 'r': int(lp[8]), 't': int(lp[9]),
            'matflags': [int(v) for v in matf.split()], 'blk': [int(v) for v in blkf.split()], 'name': name,
        })
    mat_index = {m.split(':')[0]: i for i, m in enumerate(MATERIALS)}
    matflags = {}
    for r in rows:
        matflags[r['mat']] = r['matflags']
    # air: transparent material (lu): not solid, no grass, no blocking, not liquid, not opaque, replaceable
    matflags.setdefault('a', [0, 0, 0, 0, 0, 1, 0])

    def arr(key):
        v = [0] * 256
        for r in rows:
            v[r['id']] = key(r)
        return v

    def js_arr(v):
        return '[' + ','.join(str(x) for x in v) + ']'

    out = []
    out.append('// Generated by tools/gen_blockdata.py from the b1.7.3 Block and Material tables (re/blocktable.txt).')
    out.append('// Do not edit by hand.')
    out.append('')
    out.append('export const MAT = {' + ', '.join(f"{m.split(':')[1]}: {i}" for i, m in enumerate(MATERIALS)) + '};')
    for i, flag in enumerate(['SOLID', 'CAN_GRASS', 'BLOCKS_MOVEMENT', 'LIQUID', 'OPAQUE', 'REPLACEABLE', 'BURNS']):
        v = [matflags.get(m.split(':')[0], [0] * 7)[i] for m in MATERIALS]
        out.append(f'export const MAT_{flag} = Uint8Array.from({js_arr(v)});')
    out.append('')
    out.append(f"export const EXISTS = Uint8Array.from({js_arr(arr(lambda r: 1))});")
    out.append(f"export const MATERIAL = Uint8Array.from({js_arr(arr(lambda r: mat_index[r['mat']]))});")
    out.append(f"export const OPAQUE_CUBE = Uint8Array.from({js_arr(arr(lambda r: r['o']))});")
    out.append(f"export const LIGHT_OPACITY = Uint8Array.from({js_arr(arr(lambda r: r['q']))});")
    out.append(f"export const LIGHT_VALUE = Uint8Array.from({js_arr(arr(lambda r: r['s']))});")
    out.append(f"export const TICK_ON_LOAD = Uint8Array.from({js_arr(arr(lambda r: r['n']))});")
    out.append(f"export const IS_CONTAINER = Uint8Array.from({js_arr(arr(lambda r: r['p']))});")
    out.append(f"export const IS_OPAQUE_CUBE = Uint8Array.from({js_arr(arr(lambda r: r['blk'][0]))});")
    out.append(f"export const RENDER_NORMAL = Uint8Array.from({js_arr(arr(lambda r: r['blk'][1]))});")
    out.append('')
    out.append('export const NAMES = {' + ', '.join(f"{r['id']}: {r['name']!r}" for r in rows) + '};')
    out.append('')
    path = os.path.join(ROOT, 'packs', 'BP', 'scripts', 'gen', 'blockdata.js')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', path, len(rows), 'blocks')


if __name__ == '__main__':
    main()
